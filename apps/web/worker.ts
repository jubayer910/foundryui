/**
 * Custom Worker entry (OpenNext "custom worker"): the generated .open-next/worker.js handles every request;
 * this file adds a `scheduled` handler for the Contra sales sync cron (wrangler.jsonc triggers.crons).
 *
 * The cron does not run Next code directly (the Cloudflare context only exists inside a request). It sends
 * POST /api/internal/contra-sync into this same worker's fetch handler, with the shared secret header, so
 * nothing goes over the public network and the route runs exactly like a normal request.
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- the file exists only after the OpenNext build, so expect-error would fail once it does
// @ts-ignore generated by `opennextjs-cloudflare build`, resolved by wrangler
import { default as handler } from "./.open-next/worker.js";
import { SYNC_HEADER, SYNC_PATH, syncSecret } from "./lib/contra/sync-secret";
import { withContent } from "./lib/content/rewrite";

type Env = CloudflareEnv;
// Minimal shapes of the Workers runtime types (this project does not load @cloudflare/workers-types).
type ExecutionContext = { waitUntil(p: Promise<unknown>): void; passThroughOnException(): void };
type ScheduledController = { scheduledTime: number; cron: string };
type Handler = { fetch(req: Request, env: Env, ctx: ExecutionContext): Promise<Response> };
const worker = {
  fetch: async (req: Request, env: Env, ctx: ExecutionContext) => {
    // One canonical scheme: http://ingotui.com/... answered 200 and Google indexed both versions, splitting rank.
    const url = new URL(req.url);
    if (url.protocol === "http:" && url.hostname === "ingotui.com") {
      url.protocol = "https:";
      return Response.redirect(url.toString(), 301);
    }
    // Page loads always get a full body, so an old browser copy (from before an edit) can't win with a 304.
    if (req.method === "GET" && (req.headers.get("accept") || "").includes("text/html") && (req.headers.has("if-none-match") || req.headers.has("if-modified-since"))) {
      req = new Request(req);
      req.headers.delete("if-none-match");
      req.headers.delete("if-modified-since");
    }
    return withContent(req, env, await (handler as Handler).fetch(req, env, ctx));
  },

  async scheduled(_controller: ScheduledController, env: Env, ctx: ExecutionContext) {
    const secret = await syncSecret(env);
    if (!secret) return;
    const origin = (env.BETTER_AUTH_URL || "https://ingotui.com").replace(/\/+$/, "");
    const req = new Request(origin + SYNC_PATH, { method: "POST", headers: { [SYNC_HEADER]: secret, "user-agent": "ingotui-cron" } });
    const res = await (handler as Handler).fetch(req, env, ctx);
    // Status only: the body holds counts, never tokens or buyer emails.
    if (!res.ok) console.warn("contra-sync cron:", res.status);
    await res.body?.cancel();
  },
};
export default worker;

