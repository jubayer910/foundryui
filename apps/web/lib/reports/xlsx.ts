/**
 * A minimal XLSX (SpreadsheetML) writer: inline strings, a fixed style sheet, column widths, frozen header
 * rows, stored (uncompressed) zip entries. No dependency, about 200 lines, runs the same on Workers and Node.
 *
 * Why not a library: SheetJS and ExcelJS add 400 KB to 1 MB to the Worker bundle and parse far more than we
 * write. A report workbook is a few hundred cells, so stored entries stay well under 1 MB and need no deflate.
 */

export type Style = "text" | "head" | "int" | "usd" | "pct" | "dec" | "date" | "title" | "bInt" | "bUsd" | "bPct" | "bDec" | "bText" | "note";
export type Cell = { v: string | number | null; s?: Style } | string | number | null;
export type Sheet = { name: string; widths: number[]; rows: Cell[][]; freeze?: number };

